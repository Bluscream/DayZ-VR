    inline bool CheckAll(std::span<const CodeCheck> checks, std::span<const std::uint8_t> image) noexcept
    {
        for (const auto& check : checks)
        {
            if (check.rva > image.size() || check.bytes.size() > image.size() - check.rva)
                return false;
            if (!std::equal(check.bytes.begin(), check.bytes.end(), image.subspan(check.rva).begin()))
                return false;
        }
        return true;
    }

    inline bool ValidateCurrentBuild(std::span<const std::uint8_t> image) noexcept
    {
        return CheckAll(kCurrentBuildChecks, image);
    }

    inline bool ValidateInputBuild(std::span<const std::uint8_t> image) noexcept
    {
        return CheckAll(kInputBuildChecks, image);
    }
