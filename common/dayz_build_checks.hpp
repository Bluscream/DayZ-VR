    inline bool ValidateCurrentBuild(std::span<const std::uint8_t> image) noexcept
    {
        for (const auto& check : kCurrentBuildChecks)
        {
            if (check.rva > image.size() || check.bytes.size() > image.size() - check.rva)
                return false;
            if (!std::equal(check.bytes.begin(), check.bytes.end(), image.subspan(check.rva).begin()))
                return false;
        }
        return true;
    }
